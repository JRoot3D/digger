//! The original game art, embedded in the program.
//!
//! The blobs in the repository's `assets/` directory are produced once by
//! `cargo xtask import-assets` from the upstream data tables and committed
//! (see `docs/assets.md`). This module embeds `sprites.bin`, `font.bin` and
//! `title.zz` and pulls in the generated `index.rs`, so a build needs neither
//! the upstream tree nor any file at run time.
//!
//! Access is typed: an [`ImageId`] is valid by construction, so looking up its
//! [`Image`] cannot fail; [`glyph_for`] answers `None` for a character the font
//! does not cover; [`TitlePicture::decode`] is the only fallible operation.

mod font;
mod image;
mod title;

pub use font::{GLYPH_BYTES, GLYPH_SIDE, Glyph, glyph_for};
pub use image::{Image, ImageId, ImageSize};
pub use title::{TITLE_BYTES, TitlePicture};

/// One entry of the generated sprite index: byte offsets of an image and of
/// its mask in [`SPRITES`], and the image size (`w` in units of 4 logical
/// pixels, `h` in logical pixels).
#[derive(Debug, Clone, Copy)]
pub(crate) struct SpriteEntry {
    image: u32,
    mask: u32,
    w: u8,
    h: u8,
}

// Generated by `cargo xtask import-assets`: `SPRITE_INDEX` and `GLYPH_INDEX`.
include!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../assets/index.rs"
));

/// The sprite images and masks, addressed through [`SPRITE_INDEX`].
static SPRITES: &[u8] = include_bytes!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../assets/sprites.bin"
));

/// Number of glyphs in [`FONT`].
const GLYPH_COUNT: usize = 40;

/// The 40 font glyphs of 576 bytes each; the array type checks the length at
/// compile time.
static FONT: &[u8; GLYPH_COUNT * GLYPH_BYTES] = include_bytes!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../assets/font.bin"
));

/// Length of the committed title stream (research 03 §9.1).
const TITLE_STREAM_LEN: usize = 2772;

/// The upstream zlib stream of the title picture, verbatim; the array type
/// checks the length at compile time.
static TITLE_STREAM: &[u8; TITLE_STREAM_LEN] = include_bytes!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../assets/title.zz"
));

/// Byte length of an image or mask of size `w`, `h`: `8w x 2h`.
const fn byte_len(w: u8, h: u8) -> usize {
    16 * (w as usize) * (h as usize)
}

/// Compile-time proof that every index entry lies inside the embedded blobs,
/// which is what makes [`ImageId::get`] and [`glyph_for`] infallible.
const _: () = {
    let mut i = 0;
    while i < SPRITE_INDEX.len() {
        #[expect(
            clippy::indexing_slicing,
            reason = "const evaluation: an out-of-range index fails the build"
        )]
        let entry = SPRITE_INDEX[i];
        let len = byte_len(entry.w, entry.h);
        assert!(len > 0, "sprite entry with an empty size");
        assert!(
            entry.image as usize + len <= SPRITES.len(),
            "sprite image outside sprites.bin"
        );
        assert!(
            entry.mask as usize + len <= SPRITES.len(),
            "sprite mask outside sprites.bin"
        );
        i += 1;
    }
    let mut c = 0;
    while c < GLYPH_INDEX.len() {
        #[expect(
            clippy::indexing_slicing,
            reason = "const evaluation: an out-of-range index fails the build"
        )]
        if let Some(glyph) = GLYPH_INDEX[c] {
            assert!((glyph as usize) < GLYPH_COUNT, "glyph outside font.bin");
        }
        c += 1;
    }
    // The title stream starts with the zlib header 0x78 0xDA (research 03 §9.1).
    assert!(TITLE_STREAM[0] == 0x78 && TITLE_STREAM[1] == 0xDA);
};

