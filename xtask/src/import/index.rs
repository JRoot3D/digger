//! Generator of `assets/index.rs`, the Rust source that `digger-core` pulls
//! in with `include!` (design D2).
//!
//! The text is a pure function of the planned sprite entries and glyph map,
//! so two imports of the same input produce the same bytes.

use std::fmt::Write as _;

use super::manifest::UPSTREAM_COMMIT;
use super::sprites::SpriteEntry;

/// Renders `index.rs` for `entries` (one per image number) and
/// `glyph_index` (one per character code from 32).
pub(crate) fn render(entries: &[SpriteEntry], glyph_index: &[Option<u8>]) -> String {
    let mut text = String::new();
    // Writing to a `String` cannot fail.
    let _ = write!(
        text,
        "// @generated by `cargo xtask import-assets` from upstream sobomax/digger\n\
         // {UPSTREAM_COMMIT}. Do not edit by hand; re-run the import.\n\
         //\n\
         // SPRITE_INDEX: for each image number, the byte offsets of its image and\n\
         // its mask in sprites.bin, and its size (w in units of 4 logical pixels,\n\
         // h in logical pixels); image and mask each span 8w x 2h bytes.\n\
         // GLYPH_INDEX: for each character code from 32, its glyph in font.bin.\n\
         \n\
         pub(crate) const SPRITE_INDEX: [SpriteEntry; {}] = [\n",
        entries.len()
    );
    for (number, entry) in entries.iter().enumerate() {
        let _ = writeln!(
            text,
            "    SpriteEntry {{ image: {}, mask: {}, w: {}, h: {} }}, // {number}",
            literal(entry.image),
            literal(entry.mask),
            entry.size.w,
            entry.size.h,
        );
    }
    let _ = write!(
        text,
        "];\n\npub(crate) const GLYPH_INDEX: [Option<u8>; {}] = [\n",
        glyph_index.len()
    );
    for (code, glyph) in (32u8..).zip(glyph_index) {
        let value = glyph.map_or_else(|| "None".to_owned(), |glyph| format!("Some({glyph})"));
        let _ = writeln!(
            text,
            "    {:<9} // {:?}",
            format!("{value},"),
            char::from(code)
        );
    }
    text.push_str("];\n");
    text
}

/// A decimal literal, with `_` separators from five digits on so that the
/// included source passes Clippy's `unreadable_literal`.
fn literal(value: u32) -> String {
    let digits = value.to_string();
    if digits.len() < 5 {
        return digits;
    }
    let mut out = String::new();
    for (position, digit) in digits.chars().enumerate() {
        if position > 0 && (digits.len() - position).is_multiple_of(3) {
            out.push('_');
        }
        out.push(digit);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::{literal, render};
    use crate::import::sprites::{ImageSize, SpriteEntry};

    #[test]
    fn literals_are_grouped() {
        assert_eq!(literal(0), "0");
        assert_eq!(literal(9999), "9999");
        assert_eq!(literal(10_000), "10_000");
        assert_eq!(literal(150_432), "150_432");
        assert_eq!(literal(1_234_567), "1_234_567");
    }

    #[test]
    fn index_rs_is_stable_text() {
        let entries = [
            SpriteEntry {
                image: 0,
                mask: 0,
                size: ImageSize { w: 4, h: 15 },
            },
            SpriteEntry {
                image: 960,
                mask: 12_345,
                size: ImageSize { w: 2, h: 8 },
            },
        ];
        let glyphs = [Some(39), None, Some(7), None];
        let expected = "\
// @generated by `cargo xtask import-assets` from upstream sobomax/digger
// 638125eecc2a36629b886f58d7b75253894cf3d3. Do not edit by hand; re-run the import.
//
// SPRITE_INDEX: for each image number, the byte offsets of its image and
// its mask in sprites.bin, and its size (w in units of 4 logical pixels,
// h in logical pixels); image and mask each span 8w x 2h bytes.
// GLYPH_INDEX: for each character code from 32, its glyph in font.bin.

pub(crate) const SPRITE_INDEX: [SpriteEntry; 2] = [
    SpriteEntry { image: 0, mask: 0, w: 4, h: 15 }, // 0
    SpriteEntry { image: 960, mask: 12_345, w: 2, h: 8 }, // 1
];

pub(crate) const GLYPH_INDEX: [Option<u8>; 4] = [
    Some(39), // ' '
    None,     // '!'
    Some(7),  // '\"'
    None,     // '#'
];
";
        assert_eq!(render(&entries, &glyphs), expected);
        assert_eq!(render(&entries, &glyphs), render(&entries, &glyphs));
    }
}
