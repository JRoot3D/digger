//! `assets/manifest.txt`: the SHA-256 digest and length of every file the
//! import writes (design D2; spec "Committed asset integrity").
//!
//! Format: comment lines starting with `#`, one of which names the upstream
//! commit, then one line per file, sorted by name:
//!
//! ```text
//! <64 lowercase hex digits>  <length in bytes>  <file name>
//! ```

use std::fmt::Write as _;

use sha2::{Digest as _, Sha256};

/// The upstream commit the assets are imported from (porting plan §1).
pub(crate) const UPSTREAM_COMMIT: &str = "638125eecc2a36629b886f58d7b75253894cf3d3";

/// One manifest line.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Entry {
    pub(crate) sha256: String,
    pub(crate) len: usize,
    pub(crate) name: String,
}

impl Entry {
    /// The entry describing `bytes` stored as `name`.
    pub(crate) fn of(name: &str, bytes: &[u8]) -> Self {
        Self {
            sha256: sha256_hex(bytes),
            len: bytes.len(),
            name: name.to_owned(),
        }
    }
}

/// Lowercase hexadecimal SHA-256 of `bytes`.
pub(crate) fn sha256_hex(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .fold(String::with_capacity(64), |mut hex, byte| {
            let _ = write!(hex, "{byte:02x}");
            hex
        })
}

/// Renders the manifest for `files` (name and contents), sorted by name.
pub(crate) fn render<'a>(files: impl IntoIterator<Item = (&'a str, &'a [u8])>) -> String {
    let mut entries: Vec<Entry> = files
        .into_iter()
        .map(|(name, bytes)| Entry::of(name, bytes))
        .collect();
    entries.sort_by(|a, b| a.name.cmp(&b.name));
    let mut text = format!(
        "# Digger assets, generated by `cargo xtask import-assets`; do not edit by hand.\n\
         # upstream sobomax/digger {UPSTREAM_COMMIT}\n\
         # sha256 length name\n"
    );
    for entry in entries {
        let _ = writeln!(text, "{}  {}  {}", entry.sha256, entry.len, entry.name);
    }
    text
}

/// Reads the file lines of a manifest; `None` if a line is malformed.
#[cfg(test)]
pub(crate) fn parse(text: &str) -> Option<Vec<Entry>> {
    text.lines()
        .filter(|line| !line.starts_with('#') && !line.trim().is_empty())
        .map(|line| {
            let mut fields = line.split_whitespace();
            let sha256 = fields.next()?;
            let len = fields.next()?.parse().ok()?;
            let name = fields.next()?;
            let valid = fields.next().is_none()
                && sha256.len() == 64
                && sha256
                    .bytes()
                    .all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'));
            valid.then(|| Entry {
                sha256: sha256.to_owned(),
                len,
                name: name.to_owned(),
            })
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::{Entry, UPSTREAM_COMMIT, parse, render, sha256_hex};

    #[test]
    fn sha256_known_vector() {
        assert_eq!(
            sha256_hex(b"abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
    }

    #[test]
    fn manifest_round_trip_is_sorted() {
        let text = render([("b.bin", &b"abc"[..]), ("a.bin", &b""[..])]);
        assert!(text.contains(UPSTREAM_COMMIT));
        assert_eq!(
            parse(&text),
            Some(vec![Entry::of("a.bin", b""), Entry::of("b.bin", b"abc")])
        );
        assert!(text.ends_with(
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad  3  b.bin\n"
        ));
        assert_eq!(parse("abc 3 x.bin\n"), None);
    }
}
